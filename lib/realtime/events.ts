/**
 * Centralized, typed real-time event taxonomy.
 *
 * Every event has a string name, a typed payload, and rules about what may be
 * broadcast. Payloads contain only information required by the recipient and
 * never passwords, tokens, secrets, or unsanitized content.
 *
 * Existing application event names are preserved where established
 * (e.g. BOOSTER_ASSIGNED, NEW_MESSAGE) and mapped into this taxonomy.
 */

export type RealtimeEventName =
  // Chat
  | "chat.message.created"
  | "chat.message.read"
  | "chat.typing.started"
  | "chat.typing.stopped"
  | "chat.presence.changed"
  // Notifications
  | "notification.created"
  | "notification.read"
  | "notification.all_read"
  | "notification.unread_count_changed"
  // Orders
  | "order.created"
  | "order.assigned"
  | "order.reassigned"
  | "order.started"
  | "order.status_changed"
  | "order.completed"
  |   "order.cancelled"
  | "order.updated"
  // Live page refresh signals (no data: the page refetches)
  | "live.refresh"
  | "pool.changed"
  // Access control
  | "order.access_revoked"
  // Support
  | "support.message.created"
  | "support.ticket.updated"
  | "support.ticket.assigned"
  | "support.ticket.closed";

export interface RealtimeEvent<Name extends RealtimeEventName = RealtimeEventName> {
  name: Name;
  channel: string;
  payload: RealtimeEventPayload[Name];
  /** Server-generated timestamp for dedup and ordering. */
  sentAt: string;
  /** Opaque id to detect duplicate deliveries. */
  messageId: string;
}

export type RealtimeEventPayload = {
  // Chat
  "chat.message.created": {
    messageId: string;
    conversationId: string;
    orderId: string;
    senderId: string | null;
    senderName: string | null;
    senderImage: string | null;
    content: string;
    messageType: string;
    createdAt: string;
    /**
     * Opaque id generated by the sending browser for optimistic rendering.
     * Echoed back (never persisted) so the sender can reconcile its pending
     * bubble with the confirmed message without duplicating it.
     */
    clientMessageId: string | null;
  };
  "chat.message.read": {
    conversationId: string;
    orderId: string;
    readerId: string;
    readAt: string;
    messageIds: string[];
  };
  "chat.typing.started": {
    conversationId?: string;
    orderId: string;
    userId: string;
    userName: string | null;
  };
  "chat.typing.stopped": {
    conversationId?: string;
    orderId: string;
    userId: string;
  };
  "chat.presence.changed": {
    userId: string;
    online: boolean;
    channel: string;
  };
  // Notifications
  "notification.created": {
    notificationId: string;
    type: string;
    title: string;
    message: string;
    orderId: string | null;
    createdAt: string;
  };
  "notification.read": {
    notificationId: string;
    readerId: string;
    readAt: string;
  };
  "notification.all_read": {
    userId: string;
    readAt: string;
  };
  "notification.unread_count_changed": {
    userId: string;
    unreadCount: number;
  };
  // Orders
  "order.created": {
    orderId: string;
    customerId: string;
    status: string;
    createdAt: string;
  };
  "order.assigned": {
    orderId: string;
    customerId: string;
    boosterId: string;
    assignedById: string;
    assignmentId: string;
    status: string;
    assignedAt: string;
  };
  "order.reassigned": {
    orderId: string;
    customerId: string;
    previousBoosterId: string;
    newBoosterId: string;
    assignedById: string;
    assignmentId: string;
    status: string;
    assignedAt: string;
    reason?: string;
  };
  "order.started": {
    orderId: string;
    customerId: string;
    boosterId: string;
    assignmentId: string;
    startedAt: string;
  };
  "order.status_changed": {
    orderId: string;
    customerId: string;
    boosterId: string | null;
    previousStatus: string;
    newStatus: string;
    changedAt: string;
  };
  "order.completed": {
    orderId: string;
    customerId: string;
    boosterId: string;
    assignmentId: string;
    completedAt: string;
  };
  "order.cancelled": {
    orderId: string;
    customerId: string;
    boosterId: string | null;
    assignmentId: string | null;
    reason?: string;
    cancelledAt: string;
  };
  // Access control
  "order.access_revoked": {
    orderId: string;
    reason?: string;
    revokedAt: string;
  };
  /** Something on the order changed (Riot sync, session, login, bid won...): refetch. */
  "order.updated": { orderId: string; reason: string };
  /** A page of this user may be stale: refetch (no data). */
  "live.refresh": { scope: string };
  /** The order pool changed: boosters refetch their own filtered pool (no order data). */
  "pool.changed": { reason: "added" | "removed" | "bid" };
  // Support
  "support.message.created": {
    messageId: string;
    ticketId: string;
    senderId: string | null;
    senderName: string | null;
    senderImage: string | null;
    content: string;
    isAdminReply: boolean;
    createdAt: string;
  };
  "support.ticket.updated": {
    ticketId: string;
    customerId: string;
    assignedAdminId: string | null;
    previousStatus: string;
    newStatus: string;
    updatedAt: string;
  };
  "support.ticket.assigned": {
    ticketId: string;
    customerId: string;
    adminId: string;
    assignedById: string;
    assignedAt: string;
  };
  "support.ticket.closed": {
    ticketId: string;
    customerId: string;
    closedById: string;
    closedAt: string;
  };
};
