// Helper to build rank-picker fields shared across ranked offers.
function rankField(
  key: string,
  label: string,
  rankSystemId: string,
  required = true,
  description?: string,
): GameServiceOffer['fields'][number] {
  return {
    type: 'rank-picker',
    key,
    label,
    description,
    required,
    rankSystemId,
  }
}

