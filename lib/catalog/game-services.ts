export function getGameServiceOffer(
  gameSlug: string,
  serviceSlug: string,
): GameServiceOffer | undefined {
  return gameServices.find(
    (offer) => offer.gameSlug === gameSlug && offer.serviceSlug === serviceSlug,
  )
}

export function getGameServiceOffers(gameSlug: string): GameServiceOffer[] {
  return gameServices
    .filter((offer) => offer.gameSlug === gameSlug)
    .sort((a, b) => (a.order ?? 999) - (b.order ?? 999))
}

export function isGameServiceOffer(gameSlug: string, serviceSlug: string): boolean {
  return gameServices.some(
    (offer) => offer.gameSlug === gameSlug && offer.serviceSlug === serviceSlug,
  )
}
