/**
 * Regenerate lib/catalog/lol-champions.generated.ts: every League of Legends
 * champion with its lanes, from public sources (no API key):
 *  - Riot Data Dragon (official): latest patch, champion ids, names, titles,
 *    class tags, square icons.
 *  - Meraki Analytics community dataset: the lanes each champion is played in
 *    (Data Dragon has no lane data). Missing lanes fall back to class tags.
 *
 * Run after a patch that adds a champion:
 *   npx tsx scripts/sync-lol-champions.ts
 * The output is a plain TypeScript file: the app never calls these sources
 * at runtime, and order validation always has the full list.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

type Lane = "top" | "jungle" | "mid" | "adc" | "support";

const MERAKI_LANES: Record<string, Lane> = {
  TOP: "top",
  JUNGLE: "jungle",
  MIDDLE: "mid",
  BOTTOM: "adc",
  SUPPORT: "support",
};

/** Fallback lanes from Riot class tags when no lane data is available. */
const TAG_LANES: Record<string, Lane[]> = {
  Marksman: ["adc"],
  Support: ["support"],
  Mage: ["mid"],
  Assassin: ["mid"],
  Fighter: ["top"],
  Tank: ["top"],
};

/** Stable URL-safe id: "Kai'Sa" -> "kaisa", "Nunu & Willump" -> "nunu-willump". */
export function slugify(name: string): string {
  return name
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/['.]/g, "")
    .replace(/&/g, " ")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function json<T>(url: string): Promise<T> {
  const res = await fetch(url, { signal: AbortSignal.timeout(30_000) });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return (await res.json()) as T;
}

async function main() {
  const [version] = await json<string[]>("https://ddragon.leagueoflegends.com/api/versions.json");
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`Unexpected Data Dragon version ${version}`);
  const dd = await json<{ data: Record<string, { id: string; key: string; name: string; title: string; tags: string[] }> }>(
    `https://ddragon.leagueoflegends.com/cdn/${version}/data/en_US/champion.json`
  );

  let meraki: Record<string, { positions?: string[] }> = {};
  try {
    meraki = await json("https://cdn.merakianalytics.com/riot/lol/resources/latest/en-US/champions.json");
  } catch (e) {
    console.warn(`Lane data unavailable (${(e as Error).message}); using class tags for lanes.`);
  }

  const rows = Object.values(dd.data)
    .map((c) => {
      const fromMeraki = (meraki[c.id]?.positions ?? []).map((p) => MERAKI_LANES[p]).filter((l): l is Lane => !!l);
      const lanes = fromMeraki.length ? fromMeraki : [...new Set(c.tags.flatMap((t) => TAG_LANES[t] ?? []))];
      return {
        id: slugify(c.name),
        key: Number(c.key),
        ddragonId: c.id,
        name: c.name,
        title: c.title,
        tags: c.tags,
        lanes: [...new Set(lanes)],
        laneSource: fromMeraki.length ? "meraki" : "tags",
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));

  const ids = new Set<string>();
  for (const r of rows) {
    if (!r.id || ids.has(r.id)) throw new Error(`Duplicate or empty champion id for ${r.name}`);
    ids.add(r.id);
  }
  const fallback = rows.filter((r) => r.laneSource === "tags").map((r) => r.name);

  const body = rows
    .map(
      (r) =>
        `  { id: ${JSON.stringify(r.id)}, key: ${r.key}, ddragonId: ${JSON.stringify(r.ddragonId)}, name: ${JSON.stringify(r.name)}, title: ${JSON.stringify(r.title)}, tags: ${JSON.stringify(r.tags)}, lanes: ${JSON.stringify(r.lanes)} },`
    )
    .join("\n");

  const file = `/**
 * GENERATED by scripts/sync-lol-champions.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
 * Source: Riot Data Dragon ${version} (champions, icons, class tags) and the
 * Meraki Analytics dataset (lanes).${fallback.length ? `\n * Lanes from class tags (no lane data): ${fallback.join(", ")}.` : ""}
 */
import type { LolChampionData } from "./lol-champion-types";

export const LOL_DDRAGON_VERSION = ${JSON.stringify(version)};

export const LOL_CHAMPION_DATA: LolChampionData[] = [
${body}
];
`;
  const out = join(process.cwd(), "lib/catalog/lol-champions.generated.ts");
  writeFileSync(out, file);
  console.log(`Wrote ${rows.length} champions (Data Dragon ${version}) to ${out}`);
  if (fallback.length) console.log(`Lanes from class tags for: ${fallback.join(", ")}`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
